def area_square(side):
    return side * side


def area_rect(w, h):
    """Return the area of a rectangle."""
    return w * h


def area_circle(r):
    """Return the area of a circle."""
    return 3.14159 * r * r


def circumference(r):
    """Return the circumference of a circle."""
    return 2 * 3.14159 * r
